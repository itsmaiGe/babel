"use strict";
const fs = require("node:fs"), path = require("node:path");
const ROOT = path.resolve(__dirname, "../.."), LOCALES = ["en", "zh-Hans", "zh-Hant", "ja"];
const MNEMONIC_GROUPS = [["win.path", "win.redetect", "win.cleanup", "win.details", "win.install", "win.uninstall", "win.close", "win.restart"]];
const parameters = value => [...new Set([...value.matchAll(/\{([A-Za-z][\w]*)\}/g)].map(match => match[1]))].sort();
function validateCatalogs(catalogs, languages) {
  const ids = Object.keys(catalogs.en).sort();
  for (const locale of LOCALES) {
    if (JSON.stringify(Object.keys(catalogs[locale]).sort()) !== JSON.stringify(ids)) throw new Error(`Catalog ID mismatch: ${locale}`);
    for (const id of ids) {
      const message = locale === "en" ? catalogs.en[id]?.message : catalogs[locale][id];
      if (locale === "en" && (typeof catalogs.en[id]?.description !== "string" || !catalogs.en[id].description.trim())) throw new Error(`Missing description: ${id}`);
      if (!/^(?:plugin|common|mac|win)\.[\w.]+$/.test(id) || typeof message !== "string" || !message.trim() || /<\/?[A-Za-z][^>]*>|&(?:#\d+|[a-zA-Z]+);/.test(message) || /%(?:@|[-+0#]*\d*(?:\.\d+)?[diuoxXfFeEgGcsSp])/.test(message)) throw new Error(`Invalid message: ${locale}/${id}`);
      if (JSON.stringify(parameters(message)) !== JSON.stringify(parameters(catalogs.en[id].message))) throw new Error(`Parameter mismatch: ${locale}/${id}`);
    }
    for (const group of MNEMONIC_GROUPS) {
      const used = new Set();
      for (const id of group) {
        const message = locale === "en" ? catalogs.en[id]?.message : catalogs[locale][id];
        const matches = [...message.matchAll(/&([^&\s])/gu)];
        if (matches.length !== 1 || [...message].filter(char => char === "&").length !== 1) throw new Error(`Invalid mnemonic: ${locale}/${id}`);
        const key = matches[0][1].toLocaleLowerCase("en");
        if (used.has(key)) throw new Error(`Duplicate mnemonic: ${locale}/${id}`);
        used.add(key);
      }
    }
  }
  const table = languages.map(language => `plugin.lang.${language.id}`).sort(), labels = ids.filter(id => id.startsWith("plugin.lang.")).sort();
  if (JSON.stringify(table) !== JSON.stringify(labels)) throw new Error("Translation language labels mismatch");
  return ids;
}
const quoted = value => JSON.stringify(value).replace(/\u2028/g, "\\u2028").replace(/\u2029/g, "\\u2029");
function outputs(catalogs, languages, fixtures) {
  const ids = validateCatalogs(catalogs, languages), result = new Map(), maps = {};
  for (const locale of LOCALES) {
    maps[locale] = Object.fromEntries(ids.map(id => [id, locale === "en" ? catalogs.en[id].message : catalogs[locale][id]]));
    const surface = prefix => Object.fromEntries(ids.filter(id => id.startsWith(prefix + ".") || id.startsWith("common.")).map(id => [id, maps[locale][id]]));
    result.set(`src/mod/ui/i18n/messages/${locale}.js`, `// Generated by scripts/i18n.js.\n"use strict";\nmodule.exports = Object.freeze(${JSON.stringify(surface("plugin"), null, 2)});\n`);
    const mac = Object.entries(surface("mac")).map(([id, message]) => `${quoted(id)} = ${quoted(message)};`).join("\n") + "\n";
    result.set(`installer/macos/Resources/${locale}.lproj/Localizable.strings`, mac);
    result.set(`installer/macos/Resources/${locale}.lproj/InfoPlist.strings`, `"NSAppDataUsageDescription" = ${quoted(maps[locale]["mac.privacy"])};\n"CFBundleDisplayName" = ${quoted(maps[locale]["mac.title"])};\n"CFBundleName" = ${quoted(maps[locale]["mac.title"])};\n`);
  }
  const go = LOCALES.map(locale => `${quoted(locale)}: {\n${ids.filter(id => id.startsWith("win.") || id.startsWith("common.")).map(id => `${quoted(id)}: ${quoted(maps[locale][id])},`).join("\n")}\n},`).join("\n");
  result.set("installer/internal/i18n/messages_gen.go", `// Code generated by scripts/i18n.js; DO NOT EDIT.\npackage i18n\nvar catalogs = map[string]map[string]string{\n${go}\n}\n`);
  result.set("installer/internal/i18n/testdata/locale-cases.json", JSON.stringify(fixtures, null, 2) + "\n");
  return result;
}
function generate({ check = false } = {}) {
  const catalogs = Object.fromEntries(LOCALES.map(locale => [locale, JSON.parse(fs.readFileSync(path.join(ROOT, `i18n/messages/${locale}.json`), "utf8"))]));
  const { TRANSLATION_LANGUAGES } = require(path.join(ROOT, "src/shared/defaults")), fixtures = JSON.parse(fs.readFileSync(path.join(ROOT, "i18n/locale-cases.json"), "utf8"));
  const generated = outputs(catalogs, TRANSLATION_LANGUAGES, fixtures);
  for (const [name, content] of generated) {
    const file = path.join(ROOT, name);
    if (check) { if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content) throw new Error(`Stale generated localization: ${name}`); }
    else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, content); }
  }
  return generated;
}
module.exports = { generate, outputs, validateCatalogs, LOCALES, MNEMONIC_GROUPS };
